
"""
v2_02_dataset.py

PyTorch Dataset for Hybrid Static + Temporal Model.
Loads processed folds generated by v2_01_data_pipeline.py.
"""

from pathlib import Path
import json
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader

from config import BATCH_SIZE

PROCESSED_DIR = Path("processed")


class HybridCycleDataset(Dataset):
    def __init__(self, fold=1, split="train"):
        fold_dir = PROCESSED_DIR / f"fold_{fold}"

        if split not in ("train", "valid"):
            raise ValueError("split must be 'train' or 'valid'")

        self.dynamic = np.load(fold_dir / f"X_{split}.npy")
        self.static = np.load(fold_dir / f"S_{split}.npy")
        self.target = np.load(fold_dir / f"y_{split}.npy")

        self.dynamic = torch.tensor(self.dynamic, dtype=torch.float32)
        self.static = torch.tensor(self.static, dtype=torch.float32)
        self.target = torch.tensor(self.target, dtype=torch.float32)

    def __len__(self):
        return len(self.target)

    def __getitem__(self, idx):
        return {
            "dynamic": self.dynamic[idx],
            "static": self.static[idx],
            "target": self.target[idx],
        }


def get_dataloaders(fold=1,
                    batch_size=BATCH_SIZE,
                    num_workers=0):

    train_ds = HybridCycleDataset(fold, "train")
    valid_ds = HybridCycleDataset(fold, "valid")

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=False,
    )

    valid_loader = DataLoader(
        valid_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=False,
    )

    return train_loader, valid_loader


def dataset_summary():
    meta = json.loads(
        (PROCESSED_DIR / "metadata.json").read_text()
    )

    print("=" * 60)
    print("Hybrid Dataset Summary")
    print("=" * 60)
    print("Sequence Length :", meta["sequence_length"])
    print("Dynamic Features:", len(meta["dynamic_features"]))
    print("Static Features :", len(meta["static_features"]))
    print("Target          :", meta["target"])
    print("=" * 60)


if __name__ == "__main__":

    dataset_summary()

    train_loader, valid_loader = get_dataloaders(fold=1)

    batch = next(iter(train_loader))

    print("Dynamic :", batch["dynamic"].shape)
    print("Static  :", batch["static"].shape)
    print("Target  :", batch["target"].shape)
